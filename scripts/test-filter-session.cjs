const assert = require('node:assert/strict');
const Session = require('../resources/js/filter-session.js');
const Beauty = require('../resources/js/beauty-settings.js');
let checks = 0;
function check(value, message) { assert.ok(value, message); checks++; }
const session = new Session();
check(!session.request('photo', true) && session.phase === 'selecting', 'An idle retry cannot bypass selection');
session.cancel();
check(!session.request('collage') && session.phase === 'idle', 'Removed capture mode never opens a session');
check(!session.request('photo'), 'A new photo opens selection without starting countdown');
session.select('glasses');
check(!session.request('collage'), 'Hardware/duplicate requests cannot bypass selection');
check(session.style === 'photo', 'Duplicate requests preserve the pending capture type');
session.confirm();
check(session.request('photo'), 'An explicit confirmation admits exactly one new capture');
check(!session.request('photo'), 'Repeated confirmation/click cannot start another capture');
check(!session.request('collage', true), 'Removed capture mode cannot bypass confirmation as a continuation');
check(session.request('photo', true), 'Retry preserves the confirmed photo session');
check(session.face === 'glasses', 'Sticker choice persists through processing and retry');
check(!('color' in session) && !('defaultColor' in session), 'Capture session carries no retired photo color state');
session.finish();
check(!session.request('photo'), 'Next session returns to effect selection');
check(session.face === 'none', 'New session starts without a sticker');
session.select('blush');
session.selectBeauty({ values: { ...Beauty.preset('off').values, bright: 34, warmth: 22 }, colors: { lip: '#cf2233', blush: '#ff8098' }, preset: 'custom' });
check(session.face === 'blush', 'Beauty settings do not replace the selected sticker');
check(session.beauty.values.bright === 34 && session.beauty.values.warmth === 22, 'Beauty brightness and warmth remain available without photo color presets');
check(session.beauty.colors.lip === '#cf2233' && session.beauty.colors.blush === '#ff8098', 'Beauty makeup colors remain available without photo color presets');
session.confirm();
check(session.request('photo') && session.request('photo', true), 'Beauty capture can continue through a retry');
check(session.beauty.values.bright === 34 && session.beauty.values.warmth === 22, 'Beauty settings survive capture retries');
session.cancel();
check(session.phase === 'idle', 'Cancel returns to frame selection');
assert.throws(() => session.confirm(), /selection/i, 'Confirm without selection is rejected');
console.log(`${checks + 1} capture session checks passed`);
